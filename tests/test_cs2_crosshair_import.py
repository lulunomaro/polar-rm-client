def raw_code(data, *, checksum=True):
    data = bytearray(data)
    if checksum:
        data[0] = sum(data[1:]) % 256
    n, chars = int.from_bytes(data, 'big'), []
    for _ in range(44 if len(data) == 32 else 25):
        n, digit = divmod(n, 57)
        chars.append(ALPHABET[digit])
    s = ''.join(chars)
    return 'CS' + s if len(data) == 32 else 'CSGO-' + '-'.join(s[i:i + 5] for i in range(0, 25, 5))


class CodecTests(unittest.TestCase):
    def test_real_public_vectors_decode_and_fresh_encode_without_echo(self):
        for code, expected in PUBLIC_VECTORS + [FULL_RGBA_VECTOR]:
            with self.subTest(code=code, source=PRIMARY_SOURCE):
                actual = decode_share_code(code)
                for name, value in expected.items():
                    if name not in ('Imported Code', 'Import Notes'):
                        self.assertEqual(actual[name], value, name)
                self.assertEqual(actual['Imported Code'], code)
                self.assertEqual(encode_share_code(expected), code)  # NO original code to echo.
                self.assertEqual(encode_share_code(actual), code)
                self.assertEqual(parse_external(export_json(actual)), actual)
                cfg = parse_external(export_cfg(actual))
                self.assertEqual(encode_share_code(cfg), code)
                for key in DEFAULTS:
                    if key not in ('Import Notes',):
                        self.assertEqual(cfg[key], actual[key], key)


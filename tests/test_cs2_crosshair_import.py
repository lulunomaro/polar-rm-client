    def test_new_wire_sanitation_is_explicit_and_raw_bytes_survive(self):
        b = bytearray(32)
        b[1], b[2], b[4], b[13] = 1, 100, 31, 255
        b[14:16] = (-32768).to_bytes(2, 'little', signed=True)
        b[18:22] = (0xffffffff).to_bytes(4, 'little')
        b[22], b[31] = 255, 7
        code = raw_code(b)
        v = decode_share_code(code)
        self.assertEqual((v['Reference Height'], v['CS2 Style'], v['Thickness'], v['Gap'], v['Scope Dot Scale']), (240, 9, 32, -3840, 2))
        self.assertIn('CS2规范限幅', v['Import Notes'])
        self.assertIn('保留位', v['Import Notes'])
        self.assertEqual(encode_share_code(v), code)
        v['Red'] = 41
        decoded = decode_share_code(encode_share_code(v))
        self.assertEqual(decoded['Red'], 41)
        self.assertIn('保留位', decoded['Import Notes'])

